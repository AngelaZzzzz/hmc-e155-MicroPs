int main(void) {
    // initialize everything
	configureFlash();
    configureClock();
    configureTIM6();
    configureTIM16();
	
    // enable GPIOA clock
    RCC->AHB2ENR |= (1 << 0);

    // set pin 6 to mode AF
    pinMode(6, GPIO_ALT);

    // selects TIM16 (AF14) for pin 6 by setting bits 27:24 to 1110
    GPIO->AFRL |= (14 << 24);

    // play fur elise
    int fur_elise_length = sizeof(notes) / sizeof (notes[0]);
    for (int i = 0; i < fur_elise_length; i++) {
        if (notes[i][1] == 0) {
            frequency(0);
        } else {
            frequency(notes[i][0]);
            duration(notes[i][1]);
        }
    }

    // play happy birthday
}
